type Leaves<T, Prefix extends string = ''> = {
  [K in keyof T & string]: T[K] extends string ? `${Prefix}${K}` : Leaves<T[K], `${Prefix}${K}.`>;
}[keyof T & string];

/** Every dotted key of the English dictionary. */
export type MessageKey = Leaves<typeof en>;

/** The shape every other dictionary must follow: any subset of the English keys, string values. */
export type PartialDictionary<T = typeof en> = {
  [K in keyof T]?: T[K] extends string ? string : PartialDictionary<T[K]>;
};

export type Dictionary = PartialDictionary;
